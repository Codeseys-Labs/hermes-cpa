import "C"

import (
	"encoding/json"
	"unsafe"
)

// Generated native qualification plugin for the pinned CPA plugin ABI. It
// registers browser-navigable resource routes, holds an in-memory effect counter
// and mirrors every counted effect into an append-only JSONL file, so a smoke
// can compare what the owner reported with what the native handler really did.
// It never contacts a network and never reads a credential.

type envelope struct {
	OK     bool            `json:"ok"`
	Result json.RawMessage `json:"result,omitempty"`
	Error  *envelopeError  `json:"error,omitempty"`
}

type envelopeError struct {
	Code    string `json:"code"`
	Message string `json:"message"`
}

func main() {}

//export cliproxy_plugin_init
func cliproxy_plugin_init(host *C.cliproxy_host_api, plugin *C.cliproxy_plugin_api) C.int {
	if plugin == nil {
		return 1
	}
	plugin.abi_version = C.uint32_t(abiVersion)
	plugin.call = C.cliproxy_plugin_call_fn(C.cliproxyPluginCall)
	plugin.free_buffer = C.cliproxy_plugin_free_fn(C.cliproxyPluginFree)
	plugin.shutdown = C.cliproxy_plugin_shutdown_fn(C.cliproxyPluginShutdown)
	return 0
}

//export cliproxyPluginCall
func cliproxyPluginCall(method *C.char, request *C.uint8_t, requestLen C.size_t, response *C.cliproxy_buffer) C.int {
	if response != nil {
		response.ptr = nil
		response.len = 0
	}
	if method == nil {
		writeResponse(response, errorEnvelope("invalid_method", "method is required"))
		return 1
	}
	var requestBytes []byte
	if request != nil && requestLen > 0 {
		requestBytes = C.GoBytes(unsafe.Pointer(request), C.int(requestLen))
	}
	raw, failed := dispatch(C.GoString(method), requestBytes)
	writeResponse(response, raw)
	if failed {
		return 1
	}
	return 0
}

//export cliproxyPluginFree
func cliproxyPluginFree(ptr unsafe.Pointer, size C.size_t) {
	if ptr != nil {
		C.free(ptr)
	}
	_ = size
}

//export cliproxyPluginShutdown
func cliproxyPluginShutdown() {}

func writeResponse(response *C.cliproxy_buffer, raw []byte) {
	if response == nil || len(raw) == 0 {
		return
	}
	ptr := C.CBytes(raw)
	if ptr == nil {
		return
	}
	response.ptr = ptr
	response.len = C.size_t(len(raw))
}

// okEnvelope never panics: an unencodable value becomes an error envelope.
func okEnvelope(value any) ([]byte, bool) {
	raw, err := json.Marshal(value)
	if err != nil {
		return errorEnvelope("encode_failed", "fixture result could not be encoded"), true
	}
	encoded, err := json.Marshal(envelope{OK: true, Result: raw})
	if err != nil {
		return errorEnvelope("encode_failed", "fixture envelope could not be encoded"), true
	}
	return encoded, false
}

func errorEnvelope(code, message string) []byte {
	raw, err := json.Marshal(envelope{OK: false, Error: &envelopeError{Code: code, Message: message}})
	if err != nil {
		return []byte(`{"ok":false,"error":{"code":"encode_failed","message":"fixture error"}}`)
	}
	return raw
}
