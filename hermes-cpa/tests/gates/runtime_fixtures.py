"""Generated runtime packages for installer and onboarding tests.

Pins are computed from generated bytes and written where the installer reads them:
the packaged cpa-runtime.json and the compatibility pair. They are test fixtures,
never real release metadata and never the stock CPA pin.
"""
import hashlib
import io
import json
import sys
import tarfile
from pathlib import Path

from hermes_cpa.runtime_manifest import INTEGRATION, dump_runtime_manifest, unbuilt_manifest

BINARY = b'generated executable, never launched'
NOTICES = ('LICENSE', 'THIRD_PARTY_NOTICES.md')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def write_archive(path, binary=BINARY, extra=()):
    """gzip tar holding the executable plus EXTRA TarInfo members (size filler bytes)."""
    with tarfile.open(path, 'w:gz') as tar:
        info = tarfile.TarInfo('cli-proxy-api')
        info.size = len(binary)
        tar.addfile(info, io.BytesIO(binary))
        for member in extra:
            tar.addfile(member, io.BytesIO(b'x' * member.size) if member.isfile() else None)
    return Path(path).read_bytes()


def pinned_manifest(archive, binary, glibc_max='2.17'):
    data = unbuilt_manifest()
    data['source'].update(patch_sha256='1' * 64, patch_size=1, changed_files=1)
    data['build'].update(gcc_version='generated gcc', libc_version='generated libc',
                         glibc_max=glibc_max, reproducible=True)
    data['artifact'] = dict(name=data['candidate']['asset'], archive_sha256=sha(archive),
                            archive_size=len(archive), binary_sha256=sha(binary),
                            binary_size=len(binary))
    return data


def pin_runtime(root, archive_path, binary=BINARY, *, glibc_max='2.17'):
    """Pin ARCHIVE_PATH/BINARY in ROOT/cpa-runtime.json and the compatibility pair."""
    root = Path(root)
    data = pinned_manifest(Path(archive_path).read_bytes(), binary, glibc_max)
    (root / 'cpa-runtime.json').write_bytes(dump_runtime_manifest(data))
    compatibility = root / 'compatibility.json'
    if compatibility.is_file():
        value = json.loads(compatibility.read_text())
        for pair in value['supported_pairs']:
            pair.update(integration=INTEGRATION, binary_sha256=data['artifact']['binary_sha256'],
                        archive_sha256=data['artifact']['archive_sha256'])
        compatibility.write_text(json.dumps(value))
    return data


def make_package(root, archive_path, binary=BINARY, *, glibc_max='2.17'):
    """Generated ACCEPTED package pinning ARCHIVE_PATH; returns the compatibility dict.

    Synthetic acceptance exercises the gates only; it is not candidate acceptance.
    """
    root = Path(root)
    (root / 'assets').mkdir(parents=True)
    (root / 'plugin.yaml').write_text('name: hermes-cpa\n')
    (root / 'assets/cpamc.html').write_bytes(b'generated console')
    console = sha((root / 'assets/cpamc.html').read_bytes())
    (root / 'assets/cpamc.manifest.json').write_text(json.dumps(
        dict(sha256=console, version='1.25.6', cpa_version='8.0.21')))
    for name in NOTICES:
        (root / name).write_bytes(b'generated notice')
    manifest = dict(
        candidate_status='accepted', adr_status='Accepted', tested_minimum_hermes='0.21.5',
        supported_pairs=[dict(platform='linux_amd64', cpa_version='8.0.21', console_version='1.25.6',
                              integration=INTEGRATION, console_sha256=console)],
        notice_sha256={name: sha((root / name).read_bytes()) for name in NOTICES})
    (root / 'compatibility.json').write_text(json.dumps(manifest))
    data = pin_runtime(root, archive_path, binary, glibc_max=glibc_max)
    manifest['supported_pairs'][0].update(binary_sha256=data['artifact']['binary_sha256'],
                                          archive_sha256=data['artifact']['archive_sha256'])
    return manifest


# A stand-in `gh` executable: records argv/env, answers `auth status` and streams a
# prepared asset for `release download`. Nothing here talks to the network.
FAKE_GH = """#!{python}
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
state = json.load(open(os.path.join(here, 'state.json')))
with open(state['log'], 'a') as log:
    log.write(json.dumps({'argv': sys.argv[1:], 'env': {
        name: os.environ.get(name) for name in ('GH_HOST', 'GH_REPO', 'GH_PROMPT_DISABLED')}}) + '\\n')
if sys.argv[1:3] == ['auth', 'status']:
    sys.exit(state['auth'])
if sys.argv[1:3] == ['release', 'download']:
    if state['download_exit']:
        sys.exit(state['download_exit'])
    sys.stdout.buffer.write(open(state['asset'], 'rb').read())
    sys.stdout.buffer.flush()
    sys.exit(0)
sys.exit(2)
"""


def install_fake_gh(tmp_path, monkeypatch, *, asset=None, auth=0, download_exit=0):
    """Put a fake gh alone on PATH; returns a callable listing its recorded invocations."""
    directory = Path(tmp_path) / 'fake-gh-bin'
    directory.mkdir()
    (directory / 'state.json').write_text(json.dumps(dict(
        log=str(directory / 'calls.log'), auth=auth, download_exit=download_exit,
        asset=str(asset) if asset else None)))
    script = directory / 'gh'
    script.write_text(FAKE_GH.replace('{python}', sys.executable))
    script.chmod(0o755)
    monkeypatch.setenv('PATH', str(directory))

    def calls():
        log = directory / 'calls.log'
        return [json.loads(line) for line in log.read_text().splitlines()] if log.exists() else []
    return calls
